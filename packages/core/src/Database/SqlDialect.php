<?php

declare(strict_types=1);

namespace Tihloh\Prefab\Core\Database;

use InvalidArgumentException;

/** Compile portable SQL schema declarations for Prefab-supported PDO drivers. */
final class SqlDialect
{
    private string $driver;

    public function __construct(string $driver)
    {
        $driver = strtolower(trim($driver));
        $driver = match ($driver) {
            'mariadb' => 'mysql',
            'dblib' => 'sqlsrv',
            default => $driver,
        };
        if (!in_array($driver, ['mysql', 'pgsql', 'sqlite', 'sqlsrv'], true)) {
            throw new InvalidArgumentException("Unsupported portable SQL dialect '{$driver}'.");
        }
        $this->driver = $driver;
    }

    public function driver(): string { return $this->driver; }

    public function identifier(string $name): string
    {
        TableBlueprint::assertIdentifier($name);
        return match ($this->driver) {
            'mysql' => chr(96) . $name . chr(96),
            'sqlsrv' => '[' . $name . ']',
            default => '"' . $name . '"',
        };
    }

    public function createTable(string $table, TableBlueprint $blueprint, bool $ifNotExists = true): string
    {
        $quotedTable = $this->identifier($table);
        $columns = $blueprint->columns();
        if ($columns === []) {
            throw new InvalidArgumentException('Cannot create a table without columns.');
        }
        $definitions = [];
        foreach ($columns as $name => $column) {
            $definitions[] = $this->columnSql($name, $column);
        }
        foreach ($blueprint->uniqueConstraints() as $uniqueColumns) {
            $quoted = array_map(fn(string $name): string => $this->identifier($name), $uniqueColumns);
            $definitions[] = 'UNIQUE (' . implode(', ', $quoted) . ')';
        }
        $definition = implode(', ', $definitions);
        if ($this->driver === 'sqlsrv') {
            $create = "CREATE TABLE {$quotedTable} ({$definition})";
            return $ifNotExists
                ? "IF OBJECT_ID(N'{$table}', N'U') IS NULL {$create}"
                : $create;
        }
        $modifier = $ifNotExists ? ' IF NOT EXISTS' : '';
        return "CREATE TABLE{$modifier} {$quotedTable} ({$definition})";
    }

    public function dropTable(string $table): string
    {
        $quoted = $this->identifier($table);
        return $this->driver === 'sqlsrv'
            ? "IF OBJECT_ID(N'{$table}', N'U') IS NOT NULL DROP TABLE {$quoted}"
            : "DROP TABLE IF EXISTS {$quoted}";
    }

    /** Prepared existence query: bind the table name as parameter 1. */
    public function tableExistsQuery(): string
    {
        return match ($this->driver) {
            'mysql' => "SELECT 1 FROM information_schema.tables WHERE table_schema = DATABASE() AND table_name = ?",
            'pgsql' => "SELECT 1 FROM information_schema.tables WHERE table_schema = current_schema() AND table_name = ? AND table_type = 'BASE TABLE'",
            'sqlite' => "SELECT 1 FROM sqlite_master WHERE type = 'table' AND name = ?",
            'sqlsrv' => "SELECT 1 WHERE OBJECT_ID(?, 'U') IS NOT NULL",
        };
    }

    /** @param array<string, mixed> $column */
    private function columnSql(string $name, array $column): string
    {
        $type = (string) $column['type'];
        $identifier = $this->identifier($name);
        if ($type === 'id') {
            return $identifier . ' ' . match ($this->driver) {
                'mysql' => 'BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY',
                'pgsql' => 'BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY',
                'sqlite' => 'INTEGER PRIMARY KEY AUTOINCREMENT',
                'sqlsrv' => 'BIGINT IDENTITY(1,1) PRIMARY KEY',
            };
        }

        $typeSql = $this->typeSql($column);
        $nullable = ($column['nullable'] ?? false) ? ' NULL' : ' NOT NULL';
        $default = '';
        if ($column['hasDefault'] ?? false) {
            $value = $column['default'];
            if ($value === null && !($column['nullable'] ?? false)) {
                throw new InvalidArgumentException("Column '{$name}' cannot default to NULL unless nullable.");
            }
            if ($this->driver === 'sqlsrv' && in_array($type, ['text', 'json'], true)) {
                throw new InvalidArgumentException('SQL Server text/json defaults require a driver-specific migration.');
            }
            $default = ' DEFAULT ' . $this->literal($value);
        }
        return $identifier . ' ' . $typeSql . $nullable . $default;
    }

    /** @param array<string, mixed> $column */
    private function typeSql(array $column): string
    {
        $type = (string) $column['type'];
        return match ($type) {
            'string' => ($this->driver === 'sqlsrv' ? 'NVARCHAR' : 'VARCHAR') . '(' . (int) $column['length'] . ')',
            'text' => $this->driver === 'sqlsrv' ? 'NVARCHAR(MAX)' : 'TEXT',
            'integer' => $this->driver === 'sqlite' ? 'INTEGER' : 'INT',
            'bigInteger' => $this->driver === 'sqlite' ? 'INTEGER' : 'BIGINT',
            'boolean' => match ($this->driver) {
                'mysql' => 'TINYINT(1)',
                'pgsql' => 'BOOLEAN',
                'sqlite' => 'INTEGER',
                'sqlsrv' => 'BIT',
            },
            'date' => $this->driver === 'sqlite' ? 'TEXT' : 'DATE',
            'dateTime' => match ($this->driver) {
                'mysql' => 'DATETIME',
                'pgsql' => 'TIMESTAMP',
                'sqlite' => 'TEXT',
                'sqlsrv' => 'DATETIME2',
            },
            'json' => match ($this->driver) {
                'mysql' => 'JSON',
                'pgsql' => 'JSONB',
                'sqlite' => 'TEXT',
                'sqlsrv' => 'NVARCHAR(MAX)',
            },
            'decimal' => ($this->driver === 'sqlite' ? 'NUMERIC' : 'DECIMAL')
                . '(' . (int) $column['precision'] . ', ' . (int) $column['scale'] . ')',
            default => throw new InvalidArgumentException("Unsupported portable column type '{$type}'."),
        };
    }

    private function literal(string|int|float|bool|null $value): string
    {
        if ($value === null) { return 'NULL'; }
        if (is_bool($value)) {
            return $this->driver === 'pgsql'
                ? ($value ? 'TRUE' : 'FALSE')
                : ($value ? '1' : '0');
        }
        if (is_int($value)) { return (string) $value; }
        if (is_float($value)) {
            if (!is_finite($value)) {
                throw new InvalidArgumentException('Non-finite SQL default value.');
            }
            return (string) $value;
        }
        return "'" . str_replace("'", "''", $value) . "'";
    }
}
