<?php

declare(strict_types=1);

// Dependency-free SQL compilation smoke test. Run with:
// php packages/core/tests/PortableSchemaTest.php

require_once __DIR__ . '/../src/Database/TableBlueprint.php';
require_once __DIR__ . '/../src/Database/SqlDialect.php';
require_once __DIR__ . '/../src/Database/SchemaBuilder.php';

use Tihloh\Prefab\Core\Database\SchemaBuilder;
use Tihloh\Prefab\Core\Database\SqlDialect;
use Tihloh\Prefab\Core\Database\TableBlueprint;

$expected = [
    'mysql' => ['AUTO_INCREMENT', 'TINYINT(1)', 'DECIMAL(12, 2)', 'CREATE TABLE IF NOT EXISTS'],
    'mariadb' => ['AUTO_INCREMENT', 'TINYINT(1)', 'DECIMAL(12, 2)', 'CREATE TABLE IF NOT EXISTS'],
    'pgsql' => ['GENERATED BY DEFAULT AS IDENTITY', 'BOOLEAN', 'DECIMAL(12, 2)', 'CREATE TABLE IF NOT EXISTS'],
    'sqlite' => ['INTEGER PRIMARY KEY AUTOINCREMENT', 'INTEGER', 'NUMERIC(12, 2)', 'CREATE TABLE IF NOT EXISTS'],
    'sqlsrv' => ['IDENTITY(1,1)', 'BIT', 'DECIMAL(12, 2)', "IF OBJECT_ID"],
];

foreach ($expected as $driver => $tokens) {
    $table = new TableBlueprint();
    $table->id()->string('email')->unique('email')
        ->boolean('enabled')->default('enabled', true)
        ->decimal('balance', 12, 2)
        ->json('metadata')->nullable('metadata');

    $dialect = new SqlDialect($driver);
    $sql = $dialect->createTable('users', $table);
    foreach ($tokens as $token) {
        if (!str_contains($sql, $token)) {
            throw new RuntimeException("{$driver}: missing '{$token}' in {$sql}");
        }
    }
    if (!str_contains($sql, 'UNIQUE (') || $dialect->tableExistsQuery() === '' || $dialect->dropTable('users') === '') {
        throw new RuntimeException("{$driver}: schema operation incomplete.");
    }
    echo "{$driver}: SQL compilation OK\n";
}

foreach (['bad-column', 'a.b', 'users; DROP TABLE users'] as $invalid) {
    try {
        TableBlueprint::assertIdentifier($invalid);
        throw new RuntimeException("Identifier '{$invalid}' was accepted.");
    } catch (InvalidArgumentException) {
        // Expected.
    }
}

if (in_array('sqlite', PDO::getAvailableDrivers(), true)) {
    $pdo = new PDO('sqlite::memory:');
    $schema = new SchemaBuilder($pdo);
    $schema->create('users', static function (TableBlueprint $table): void {
        $table->id()->string('email')->unique('email')->boolean('enabled')->default('enabled', true);
    });
    if (!$schema->hasTable('users')) {
        throw new RuntimeException('SQLite table was not created.');
    }
    $pdo->exec("INSERT INTO users (email) VALUES ('example@test.invalid')");
    $schema->dropIfExists('users');
    if ($schema->hasTable('users')) {
        throw new RuntimeException('SQLite table was not dropped.');
    }
    echo "sqlite: live schema operations OK\n";
} else {
    echo "sqlite: integration test skipped (pdo_sqlite not installed)\n";
}

echo "Portable schema smoke test completed\n";
